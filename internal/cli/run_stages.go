// stageFlags carries the flags of the implemented run stages.
type stageFlags struct {
	url       string
	run       string
	programme string
	title     string
	coverage  string
	out       string
	template  string
	force     bool
	endpoint  string
	model     string
	attempts  int
	maxInput  int
	all       bool
}

func newStageFlags(name string) (*flag.FlagSet, *stageFlags) {
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	f := &stageFlags{}
	fs.StringVar(&f.url, "url", "", "official https URL the PDF was downloaded from")
	fs.StringVar(&f.run, "run", "", "run directory (default: runs/<programme>)")
	fs.StringVar(&f.programme, "programme", "", "short programme id used by the run (e.g. pp)")
	fs.StringVar(&f.title, "title", "", "display name of the programme")
	fs.StringVar(&f.coverage, "coverage", "numbers", "proposal numbering: numbers or items")
	fs.StringVar(&f.out, "out", "", "output path (build: defaults to the manifest view)")
	fs.StringVar(&f.template, "template", runview.TemplatePath, "view template")
	fs.BoolVar(&f.force, "force", false, "replace a view that was not generated by this command")
	fs.StringVar(&f.endpoint, "endpoint", "", "OpenAI-compatible base URL (default: $ATLAS_ENDPOINT)")
	fs.StringVar(&f.model, "model", "", "model identifier (default: $ATLAS_MODEL)")
	fs.IntVar(&f.attempts, "attempts", 3, "generation attempts, repairing the gate findings between them")
	fs.IntVar(&f.maxInput, "max-input-bytes", summarize.DefaultMaxInput, "extraction bytes sent to the model")
	fs.BoolVar(&f.all, "all", false, "summarise every programme of the run")
	return fs, f
}

// extractCommand turns a published PDF into provenance, page-marked extraction,
// the manifest entry and an unfilled summary skeleton.
func extractCommand() stageCommand {
	return stageCommand{name: "extract", positional: 1, flags: newStageFlags, run: func(pos []string, f *stageFlags, w io.Writer) int {
		pdf := pos[0]
		if f.url == "" || f.programme == "" {
			fmt.Fprintln(w, "manifesto-atlas extract: -url and -programme are required")
			return exitUsage
		}
		run := f.run
		if run == "" {
			run = filepath.Join("runs", f.programme)
		}
		pdf, code := sourcePDF(pdf, run, f.url, w)
		if code != exitOK {
			return code
		}
		prov, pages, err := runsource.Extract(run, pdf, f.url, runsource.OS())
		if err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		base := strings.TrimSuffix(prov.File, filepath.Ext(prov.File))
		textPath := filepath.Join(run, "text", base+".txt")
		sourcePath := filepath.Join(run, base+".md")
		title := f.title
		if title == "" {
			title = f.programme
		}
		summaryPath := filepath.Join(run, "Resumen-"+title+".md")

		if err := os.MkdirAll(filepath.Join(run, "text"), 0o755); err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		if err := os.WriteFile(textPath, []byte(strings.Join(pages, "\f")), 0o644); err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		if err := os.WriteFile(sourcePath, runsource.Marked(pages), 0o644); err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		if _, err := os.Stat(summaryPath); err != nil {
			scaffold := runsource.Scaffold(f.programme, title, prov, runsource.Sections(pages))
			if err := os.WriteFile(summaryPath, scaffold, 0o644); err != nil {
				fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
				return exitFailed
			}
		}
		spec, err := runsource.Register(run, f.programme, title, filepath.Base(sourcePath),
			filepath.Base(summaryPath), prov, runsource.CountSourceProposals(pages))
		if err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		switch f.coverage {
		case "numbers", "items":
			for i := range spec.Documents {
				if spec.Documents[i].Programme == f.programme {
					spec.Documents[i].Coverage = f.coverage
				}
			}
			if err := runmanifest.Save(run, spec); err != nil {
				fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
				return exitFailed
			}
		default:
			fmt.Fprintln(w, "manifesto-atlas extract: -coverage must be numbers or items")
			return exitUsage
		}

		if err := os.WriteFile(filepath.Join(run, "SOURCES.md"), runsource.SourcesMarkdown(spec), 0o644); err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}
		if err := ensureCheckFiles(run); err != nil {
			fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
			return exitFailed
		}

		fmt.Fprintf(w, "extracted %d pages from %s\n", prov.Pages, prov.File)
		fmt.Fprintf(w, "  provenance  %s\n", prov.URL)
		fmt.Fprintf(w, "  bytes       %d\n  sha256      %s\n", prov.Bytes, prov.SHA256)
		fmt.Fprintf(w, "  text        %s\n  source      %s\n  summary     %s\n", textPath, sourcePath, summaryPath)
		fmt.Fprintf(w, "  proposals   %d numbered items in the source\n", runsource.CountSourceProposals(pages))
		fmt.Fprintf(w, "next: write the summary (remove every %s marker), then `validate-content %s`\n",
			runsource.ScaffoldMarker, run)
		return exitOK
	}}
}

// ensureCheckFiles creates the empty curated-data files a run needs, so the gate
// has something to read from the first day instead of failing on a missing path.
func ensureCheckFiles(run string) error {
	files := map[string]string{
		"checks/claims.tsv": "# programa\tpáginas\tfragmento literal que debe aparecer en esas páginas\n",
		"checks/allow.tsv":  "# código\tfichero\tfragmento del detalle\tmotivo de la excepción\n",
	}
	for name, body := range files {
		path := filepath.Join(run, name)
		if _, err := os.Stat(path); err == nil {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// sourcePDF returns the local PDF to analyse. With no path it downloads from the
// official URL into a cache keyed by the hash, so the pipeline needs no manual
// step and the same bytes are reused across runs.
func sourcePDF(pdf, run, url string, w io.Writer) (string, int) {
	if strings.TrimSpace(pdf) != "" && pdf != "auto" {
		return pdf, exitOK
	}
	fmt.Fprintf(w, "  fetching    %s\n", url)
	cache := filepath.Join(run, "..", "..", ".cache", "sources")
	path, sum, err := runsource.Fetch(context.Background(), url, cache, nil)
	if err != nil {
		fmt.Fprintf(w, "manifesto-atlas extract: %v\n", err)
		return "", exitFailed
	}
	fmt.Fprintf(w, "  downloaded  %s\n  sha256      %s\n", path, sum)
	return path, exitOK
}

// summarizeCommand writes the summary of a programme with a configured model and
// repairs it until the gate accepts it, so no human has to write prose.
func summarizeCommand() stageCommand {
	return stageCommand{name: "summarize", positional: 1, flags: newStageFlags, run: func(pos []string, f *stageFlags, w io.Writer) int {
		run := pos[0]
		spec, err := runmanifest.Load(run)
		if err != nil {
			fmt.Fprintf(w, "manifesto-atlas summarize: %v\n", err)
			return exitFailed
		}
		endpoint := firstNonEmpty(f.endpoint, os.Getenv("ATLAS_ENDPOINT"))
		model := firstNonEmpty(f.model, os.Getenv("ATLAS_MODEL"))
		if endpoint == "" || model == "" {
			fmt.Fprintln(w, "manifesto-atlas summarize: set -endpoint/-model or ATLAS_ENDPOINT and ATLAS_MODEL")
			fmt.Fprintln(w, "  (no default is used on purpose: the model is an operator decision)")
			return exitUsage
		}
		programmes := []string{f.programme}
		if f.all {
			programmes = programmes[:0]
			for _, d := range spec.Documents {
				programmes = append(programmes, d.Programme)
			}
		}
		if len(programmes) == 1 && programmes[0] == "" {
			fmt.Fprintln(w, "manifesto-atlas summarize: pass -programme ID or -all")
			return exitUsage
		}
		failed := 0
		for _, programme := range programmes {
			res, err := summarize.Run(context.Background(), summarize.Config{
				BaseURL: endpoint, Model: model, APIKey: os.Getenv("ATLAS_API_KEY"),
				Attempts: f.attempts, MaxInput: f.maxInput,
				TracePath: filepath.Join(run, "summarize-"+programme+".json"),
			}, run, programme)
			if err != nil {
				fmt.Fprintf(w, "manifesto-atlas summarize %s: %v\n", programme, err)
				return exitFailed
			}
			status := "accepted by the gate"
			if !res.Resolved {
				status = "still failing the gate"
				failed++
			}
			fmt.Fprintf(w, "summarize %s: %d attempt(s), %s\n", programme, res.Attempts, status)
			for _, issue := range res.Issues {
				fmt.Fprintf(w, "  FAIL %s\n", issue)
			}
		}
		if failed > 0 {
			fmt.Fprintf(w, "manifesto-atlas summarize: %d programme(s) need review\n", failed)
			return exitFailed
		}
		return exitOK
	}}
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if strings.TrimSpace(v) != "" {
			return v
		}
	}
	return ""
}

// validateContent runs the deterministic gate and writes the verification report.
func validateContent() stageCommand {
	return stageCommand{name: "validate-content", positional: 1, flags: newStageFlags, run: func(pos []string, _ *stageFlags, w io.Writer) int {
		run := pos[0]
		report, err := runcheck.Verify(run)
		if err != nil {
			fmt.Fprintf(w, "manifesto-atlas validate-content: %v\n", err)
			return exitFailed
		}
		for _, line := range report.Summary() {
			fmt.Fprintln(w, line)
		}
		for _, issue := range report.Issues {
			fmt.Fprintln(w, "  FAIL", issue)
		}
		if err := os.WriteFile(filepath.Join(run, "Verificacion.md"), []byte(report.Markdown()), 0o644); err != nil {
			fmt.Fprintf(w, "manifesto-atlas validate-content: %v\n", err)
			return exitFailed
		}
		if !report.OK() {
			fmt.Fprintf(w, "manifesto-atlas validate-content: %d issues (report written to Verificacion.md)\n", len(report.Issues))
			return exitFailed
		}
		fmt.Fprintln(w, "manifesto-atlas validate-content: OK (report written to Verificacion.md)")
		return exitOK
	}}
}

// buildCommand renders the single-file view of a run.
func buildCommand() stageCommand {
	return stageCommand{name: "build", positional: 1, flags: newStageFlags, run: func(pos []string, f *stageFlags, w io.Writer) int {
		run := pos[0]
		spec, err := runmanifest.Load(run)
		if err != nil {
			fmt.Fprintf(w, "manifesto-atlas build: %v\n", err)
			return exitFailed
		}
		out := f.out
		if out == "" {
			if spec.View == "" {
				out = filepath.Join(run, "Programas-electorales.html")
			} else {
				out = filepath.Join(run, spec.View)
			}
		}
		if err := runview.Build(run, out, f.template, f.force); err != nil {
			fmt.Fprintf(w, "manifesto-atlas build: %v\n", err)
			return exitFailed
		}
		// Record the view only when the gate can resolve it from the run directory.
		if rel, err := filepath.Rel(run, out); err == nil && !strings.HasPrefix(rel, "..") {
			spec.View = rel
			if err := runmanifest.Save(run, spec); err != nil {
				fmt.Fprintf(w, "manifesto-atlas build: %v\n", err)
				return exitFailed
			}
		} else {
			fmt.Fprintf(w, "note: %s is outside the run, so the gate will not check its embedding\n", out)
		}
		fmt.Fprintf(w, "view written to %s\n", out)
		return exitOK
	}}
}

// processCommand runs the whole pipeline without human steps: extract, summarise
// with the configured model, verify and render. Any failing step stops it.
func processCommand() stageCommand {
	return stageCommand{name: "process", positional: 0, flags: newStageFlags, run: func(pos []string, f *stageFlags, w io.Writer) int {
		pdf := "auto"
		if len(pos) == 1 {
			pdf = pos[0]
		}
		if f.url == "" || f.programme == "" {
			fmt.Fprintln(w, "manifesto-atlas process: -url and -programme are required")
			return exitUsage
		}
		run := f.run
		if run == "" {
			run = filepath.Join("runs", f.programme)
		}
		if f.endpoint == "" {
			f.endpoint = os.Getenv("ATLAS_ENDPOINT")
		}
		if f.model == "" {
			f.model = os.Getenv("ATLAS_MODEL")
		}
		if f.endpoint == "" || f.model == "" {
			fmt.Fprintln(w, "manifesto-atlas process: set -endpoint/-model or ATLAS_ENDPOINT and ATLAS_MODEL")
			return exitUsage
		}
		f.run = run
		f.all = true

		steps := []struct {
			label string
			cmd   stageCommand
			args  []string
		}{
			{"extract", extractCommand(), []string{pdf}},
			{"summarize", summarizeCommand(), []string{run}},
			{"validate-content", validateContent(), []string{run}},
			{"build", buildCommand(), []string{run}},
			// The embedding check can only pass once the view exists.
			{"validate-content (vista)", validateContent(), []string{run}},
		}
		for _, step := range steps {
			fmt.Fprintf(w, "process: %s\n", step.label)
			if code := step.cmd.run(step.args, f, w); code != exitOK {
				fmt.Fprintf(w, "process: stopped at %s (exit %d)\n", step.label, code)
				return code
			}
		}
		fmt.Fprintln(w, "process: done — the run has a verified summary and a self-contained view")
		return exitOK
	}}
}
