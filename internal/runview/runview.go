// Package runview builds the single-file view of a run.
//
// The view is generated, not hand-written: every programme becomes a tab, every
// "##" of its summary becomes a collapsible section and every list item a card.
// The full summary, the verification report and the provenance travel inside one
// HTML file, so the page needs no sibling document to be read.
package runview

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/jparrill/manifesto-atlas/internal/mdrender"
	"github.com/jparrill/manifesto-atlas/internal/runmanifest"
)

// generatedMarker identifies a view produced by this package, so a hand-made
// view is never overwritten by accident.
const generatedMarker = "<!-- generated by manifesto-atlas build -->"

// TemplatePath is the project template filled by Build.
const TemplatePath = "templates/view.html"

// PayloadPlaceholder is replaced with the JSON payload.
const PayloadPlaceholder = "/*__PAYLOAD__*/"

// Card is one proposal or line of a section.
type Card struct {
	Text string `json:"text"`
}

// Section is one collapsible block of a summary.
type Section struct {
	Title string `json:"title"`
	Cards []Card `json:"cards"`
}

// Programme is one tab of the view.
type Programme struct {
	ID             string    `json:"id"`
	Title          string    `json:"title"`
	Meta           string    `json:"meta"`
	URL            string    `json:"url"`
	SHA256         string    `json:"sha256"`
	Sections       []Section `json:"sections"`
	SummaryHTML    string    `json:"summaryHtml"`
	Verification   string    `json:"verificationHtml"`
	VerificationOK bool      `json:"verification"`
}

// Embedded is one document carried inside the payload, in the shape the gate
// checks (the same one a hand-made view uses).
type Embedded struct {
	Label string `json:"label"`
	Title string `json:"title"`
	HTML  string `json:"html"`
}

// Chrome is the data the template needs to draw the tabs and the cards.
type Chrome struct {
	Run        string            `json:"run"`
	Programmes []ChromeProgramme `json:"programmes"`
}

// ChromeProgramme is one tab without the document bodies.
type ChromeProgramme struct {
	ID       string    `json:"id"`
	Title    string    `json:"title"`
	Meta     string    `json:"meta"`
	URL      string    `json:"url"`
	SHA256   string    `json:"sha256"`
	Sections []Section `json:"sections"`
}

var (
	heading = regexp.MustCompile(`^#{1,3}\s+(.*)$`)
	item    = regexp.MustCompile(`^(?:[-*]\s+|\d{1,3}[.)]\s+)`)
)

// Sections parses the Markdown of a summary into view sections.
func Sections(md string) []Section {
	var out []Section
	var current *Section
	flush := func() {
		if current != nil && (current.Title != "" || len(current.Cards) > 0) {
			out = append(out, *current)
		}
		current = nil
	}
	for _, line := range strings.Split(md, "\n") {
		t := strings.TrimSpace(line)
		switch {
		case t == "":
			continue
		case heading.MatchString(t) && strings.HasPrefix(t, "# ") &&
			!strings.HasPrefix(t, "## "):
			continue
		case heading.MatchString(t) && strings.HasPrefix(t, "## "):
			flush()
			title := strings.TrimSpace(strings.TrimPrefix(t, "## "))
			current = &Section{Title: title}
		case strings.HasPrefix(t, "<!--"):
			continue
		case t == "---":
			continue
		case item.MatchString(t):
			if current == nil {
				current = &Section{}
			}
			current.Cards = append(current.Cards, Card{Text: t})
		default:
			if current == nil {
				current = &Section{}
			}
			if len(current.Cards) == 0 && current.Title == "" {
				current.Title = t
				continue
			}
			current.Cards = append(current.Cards, Card{Text: t})
		}
	}
	flush()
	if out == nil {
		out = []Section{}
	}
	for i := range out {
		if out[i].Cards == nil {
			out[i].Cards = []Card{}
		}
	}
	return out
}

// Build renders the run into a single self-contained HTML file.
func Build(runDir, outPath, templatePath string, force bool) error {
	spec, err := runmanifest.Load(runDir)
	if err != nil {
		return err
	}
	tpl, err := os.ReadFile(templatePath)
	if err != nil {
		return fmt.Errorf("read template: %w", err)
	}
	if !strings.Contains(string(tpl), PayloadPlaceholder) {
		return fmt.Errorf("template %s has no %s placeholder", templatePath, PayloadPlaceholder)
	}

	payload := map[string]any{}
	chrome := Chrome{Run: spec.Name}
	for _, doc := range spec.Documents {
		summary, err := os.ReadFile(filepath.Join(runDir, doc.Summary))
		if err != nil {
			return fmt.Errorf("read %s: %w", doc.Summary, err)
		}
		cp := ChromeProgramme{
			ID:       doc.Programme,
			Title:    titleOf(doc),
			Meta:     metaOf(doc, summary),
			Sections: Sections(string(summary)),
		}
		for _, src := range spec.Sources {
			if src.Programme == doc.Programme {
				cp.URL, cp.SHA256 = src.URL, src.SHA256
				cp.Meta = fmt.Sprintf("%s · %d páginas", cp.Meta, src.Pages)
			}
		}
		docs := []Embedded{{Label: "Resumen completo", Title: "Resumen · " + cp.Title,
			HTML: mdrender.Render(string(summary))}}
		for _, name := range []string{VerificationPath(doc), "Verificacion.md"} {
			if raw, err := os.ReadFile(filepath.Join(runDir, name)); err == nil {
				docs = append(docs, Embedded{Label: "Informe de verificación",
					Title: "Verificación · " + cp.Title, HTML: mdrender.Render(string(raw))})
				break
			}
		}
		if cp.Sections == nil {
			cp.Sections = []Section{}
		}
		payload[doc.Programme] = docs
		chrome.Programmes = append(chrome.Programmes, cp)
	}

	if raw, err := os.ReadFile(filepath.Join(runDir, "SOURCES.md")); err == nil {
		payload["sources"] = Embedded{Label: "Fuentes y procedencia", Title: "Fuentes y procedencia",
			HTML: mdrender.Render(string(raw))}
	}
	payload["view"] = chrome

	blob, err := json.Marshal(payload)
	if err != nil {
		return err
	}
	// Keep the JSON inert inside the script element.
	safe := strings.ReplaceAll(string(blob), "</", `<\/`)
	html := strings.Replace(string(tpl), PayloadPlaceholder, safe, 1)
	if existing, err := os.ReadFile(outPath); err == nil && !strings.Contains(string(existing), generatedMarker) && !force {
		return fmt.Errorf("%s exists and was not generated by this command; pass -force to replace it", outPath)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(outPath, []byte(html), 0o644)
}

// VerificationPath is where validate-content writes the report of a programme.
func VerificationPath(doc runmanifest.Document) string {
	base := strings.TrimSuffix(doc.Summary, filepath.Ext(doc.Summary))
	return "Verificacion-" + base + ".md"
}

func titleOf(doc runmanifest.Document) string {
	if doc.Title != "" {
		return doc.Title
	}
	return doc.Programme
}

func metaOf(doc runmanifest.Document, summary []byte) string {
	for _, line := range strings.Split(string(summary), "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "| Propuestas |") || strings.HasPrefix(t, "| Documento |") {
			parts := strings.Split(t, "|")
			if len(parts) >= 3 {
				return strings.TrimSpace(parts[2])
			}
		}
	}
	return fmt.Sprintf("programa %s", doc.Programme)
}
