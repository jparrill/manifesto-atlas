func TestSections(t *testing.T) {
	md := `# Título del programa

| Dato | Valor |
|---|---|
| Páginas | 66 |

## Ceuta y Melilla [p. 7]

**1.** «Recuperar Ceuta para los ceutíes»: expulsión y militarización. [p. 7]

## Vivienda — pp. 23-25

1. «Derogación de la Ley de Vivienda» [p. 23]
2. IVA del 0 % en la primera vivienda [p. 24]
`
	t.Run("When a summary has bracketed and dashed page references they should split out", func(t *testing.T) {
		got := Sections(md)
		if len(got) != 2 {
			t.Fatalf("sections = %d, want 2: %+v", len(got), got)
		}
		if got[0].Title != "Ceuta y Melilla" || got[0].Page != "p. 7" {
			t.Fatalf("first section = %q / %q", got[0].Title, got[0].Page)
		}
		if got[1].Page != "pp. 23-25" {
			t.Fatalf("second page = %q", got[1].Page)
		}
	})
	t.Run("When a line quotes the document the label should be the literal", func(t *testing.T) {
		got := Sections(md)
		if got[0].Cards[0].Label != "Recuperar Ceuta para los ceutíes" {
			t.Fatalf("label = %q", got[0].Cards[0].Label)
		}
		if !strings.Contains(got[0].Cards[0].HTML, "<strong>1.</strong>") {
			t.Fatalf("card body not rendered: %q", got[0].Cards[0].HTML)
		}
	})
	t.Run("When the summary is empty it should return no sections", func(t *testing.T) {
		if got := Sections(""); len(got) != 0 {
			t.Fatalf("sections = %+v", got)
		}
	})
}

func TestBuild(t *testing.T) {
	dir := t.TempDir()
	template := filepath.Join("..", "..", "templates", "view.html")
	write := func(name, body string) {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir: %v", err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatalf("write: %v", err)
		}
	}
	write("pp.md", "<!-- page 1 -->\n1. Vivienda.\n")
	write("Resumen-PP.md", "# PP\n\n## Vivienda [p. 1]\n\n1. «Construir vivienda pública» [p. 1]\n")
	write("Verificacion-Resumen-PP.md", "# Verificación\n\n| ok |\n")
	write("SOURCES.md", "# Fuentes\n\n| pp | https://example.org/p.pdf |\n")
	write("run.json", `{"name":"prueba","claims":"checks/claims.tsv","view":"vista.html",
  "sources":[{"programme":"pp","url":"https://example.org/p.pdf","file":"p.pdf","bytes":10,
    "sha256":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa","pages":1}],
  "documents":[{"programme":"pp","source":"pp.md","summary":"Resumen-PP.md","proposals":1,"title":"PP"}]}`)

	t.Run("When a run is built every document should travel inside the file", func(t *testing.T) {
		out := filepath.Join(dir, "vista.html")
		if err := Build(dir, out, template, false); err != nil {
			t.Fatalf("Build: %v", err)
		}
		raw, err := os.ReadFile(out)
		if err != nil {
			t.Fatalf("read: %v", err)
		}
		page := string(raw)
		for _, want := range []string{
			"<!-- generated by manifesto-atlas build -->",
			`<script type="application/json" id="embedded-docs">`,
			`id="viewer-body"`,
			"Informe de verificación",
			"Fuentes y procedencia",
		} {
			if !strings.Contains(page, want) {
				t.Fatalf("view misses %q", want)
			}
		}
		if strings.Contains(page, `href="Resumen-PP.md"`) || strings.Contains(page, `href="pp.md"`) {
			t.Fatalf("view links a sibling file")
		}
	})
	t.Run("When the target was not generated by this command it should refuse", func(t *testing.T) {
		out := filepath.Join(dir, "hecho-a-mano.html")
		if err := os.WriteFile(out, []byte("<html>a mano</html>"), 0o644); err != nil {
			t.Fatalf("write: %v", err)
		}
		if err := Build(dir, out, template, false); err == nil {
			t.Fatalf("expected a refusal")
		}
		if err := Build(dir, out, template, true); err != nil {
			t.Fatalf("force should replace it: %v", err)
		}
	})
	t.Run("When the template has no payload placeholder it should fail", func(t *testing.T) {
		bad := filepath.Join(dir, "plantilla.html")
		if err := os.WriteFile(bad, []byte("<html></html>"), 0o644); err != nil {
			t.Fatalf("write: %v", err)
		}
		if err := Build(dir, filepath.Join(dir, "x.html"), bad, true); err == nil {
			t.Fatalf("expected a template error")
		}
	})
	t.Run("When the template is rendered its script should be valid JavaScript", func(t *testing.T) {
		node, err := exec.LookPath("node")
		if err != nil {
			t.Skip("node not available")
		}
		raw, err := os.ReadFile(template)
		if err != nil {
			t.Fatalf("read template: %v", err)
		}
		page := string(raw)
		i := strings.LastIndex(page, "<script>")
		j := strings.LastIndex(page, "</script>")
		if i < 0 || j < i {
			t.Fatalf("template has no script block")
		}
		script := filepath.Join(t.TempDir(), "tpl.mjs")
		if err := os.WriteFile(script, []byte(page[i+len("<script>"):j]), 0o644); err != nil {
			t.Fatalf("write script: %v", err)
		}
		if out, err := exec.Command(node, "--check", script).CombinedOutput(); err != nil {
			t.Fatalf("template script does not parse: %v\n%s", err, out)
		}
	})
}
